#!/bin/zsh
# Builds PromptPad.app and installs it to ~/Applications.
#   ./build.sh               build for this Mac and install
#   ./build.sh --universal   Apple silicon + Intel
#   ./build.sh --no-install  only build (build/PromptPad.app)
#   ./build.sh --public      leave out personal/ (what a published build contains)
# Personal add-ons in personal/<name>/ (and shared ones in addons/<name>/) are built in when present:
# <name>/layout.json is merged on top of the default layout, <name>/*.swift is compiled, and any
# `final class X: PadAddon` is started. personal/build.env can set BUNDLE_ID, SIGN_IDENTITY and LANGUAGE
# (the interface language until changed in the menu: auto = follow macOS, zh, en).
set -e
cd "$(dirname "$0")"
UNIVERSAL=0; INSTALL=1; PUBLIC=0
for a in "$@"; do case $a in --universal) UNIVERSAL=1;; --no-install) INSTALL=0;; --public) PUBLIC=1;; esac; done
(( PUBLIC )) || { [ -f personal/build.env ] && source personal/build.env }
BUNDLE_ID=${BUNDLE_ID:-io.github.promptpad.PromptPad}
SIGN_IDENTITY=${SIGN_IDENTITY:-PromptPad Local Signing}
VERSION=${VERSION:-3.0}
LANGUAGE=${LANGUAGE:-auto}

APP=build/PromptPad.app
rm -rf build && mkdir -p build/gen "$APP/Contents/MacOS" "$APP/Contents/Resources/addons"

# Add-ons: their Swift files, and the classes to start.
setopt null_glob
if (( PUBLIC )); then ADDON_DIRS=(addons/*(/)); else ADDON_DIRS=(personal/*(/) addons/*(/)); fi
ADDON_SRC=()
for d in $ADDON_DIRS; do ADDON_SRC+=($d/*.swift); done
{
  echo "// Generated by build.sh: the code add-ons in this build."
  echo "let installedAddons: [PadAddon] = ["
  if (( ${#ADDON_SRC} )); then
    grep -ho 'final class [A-Za-z0-9_]*: *PadAddon' $ADDON_SRC | awk '{print $3}' | tr -d ':' | sed 's/.*/    &(),/'
  fi
  echo "]"
} > build/gen/Addons.generated.swift

SOURCES=(Sources/*.swift $ADDON_SRC build/gen/Addons.generated.swift)
if (( UNIVERSAL )); then
  swiftc -O -target arm64-apple-macos14 $SOURCES -o build/PromptPad-arm64
  swiftc -O -target x86_64-apple-macos14 $SOURCES -o build/PromptPad-x86_64
  lipo -create build/PromptPad-arm64 build/PromptPad-x86_64 -output "$APP/Contents/MacOS/PromptPad"
else
  swiftc -O -target $(uname -m)-apple-macos14 $SOURCES -o "$APP/Contents/MacOS/PromptPad"
fi

sed -e "s/__BUNDLE_ID__/$BUNDLE_ID/" -e "s/__VERSION__/$VERSION/g" -e "s/__LANGUAGE__/$LANGUAGE/" Info.plist > "$APP/Contents/Info.plist"
cp -R Resources/ "$APP/Contents/Resources/"
for d in $ADDON_DIRS; do [ -f $d/layout.json ] && cp $d/layout.json "$APP/Contents/Resources/addons/$(basename $d).json"; done

# Same certificate every build = macOS keeps the permissions. Without one, sign ad hoc
# (then macOS asks for the permissions again after each rebuild; scripts/make-signing-cert.sh fixes that).
if security find-certificate -c "$SIGN_IDENTITY" >/dev/null 2>&1; then
  END=$(security find-certificate -c "$SIGN_IDENTITY" -p | openssl x509 -noout -enddate 2>/dev/null | cut -d= -f2)
  if [ -n "$END" ] && ! security find-certificate -c "$SIGN_IDENTITY" -p | openssl x509 -noout -checkend $((90 * 86400)) >/dev/null 2>&1; then
    echo "Note: the signing certificate \"$SIGN_IDENTITY\" expires on $END. Delete it in Keychain Access and run ./scripts/make-signing-cert.sh."
  fi
  if ! codesign --force --sign "$SIGN_IDENTITY" "$APP" 2>build/codesign.log; then
    echo "Signing with \"$SIGN_IDENTITY\" failed ($(head -1 build/codesign.log)); signing ad hoc instead (macOS will ask for the permissions again)."
    codesign --force --sign - "$APP"
  fi
else
  codesign --force --sign - "$APP"
fi
NAMES=(); for d in $ADDON_DIRS; do NAMES+=(${d:t}); done
echo "Built: $APP (add-ons: ${NAMES:-none})"

if (( INSTALL )); then
  mkdir -p ~/Applications
  pkill -x PromptPad 2>/dev/null || true
  rm -rf ~/Applications/PromptPad.app
  cp -R "$APP" ~/Applications/
  echo "Installed: ~/Applications/PromptPad.app"
fi
